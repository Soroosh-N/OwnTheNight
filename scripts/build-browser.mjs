import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

// Bundle this project's simple, static ES modules into a classic browser
// script. Classic scripts and inline HTML work under file:// without a server.
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const modules=new Map(),ordered=[];
function compile(file){
 const id=path.relative(root,file).split(path.sep).join('/');
 if(modules.has(id))return id;
 modules.set(id,true);
 let source=fs.readFileSync(file,'utf8'),names=[];
 source=source.replace(/^import\s+(\*\s+as\s+\w+|\{[^}]+\})\s+from\s+['"]([^'"]+)['"];?\r?$/gm,(_,binding,relative)=>{
  const dependency=compile(path.resolve(path.dirname(file),relative));
  const declaration=binding.startsWith('*')?binding.replace(/^\*\s+as\s+/,''):binding.replace(/\bas\b/g,':');
  return `const ${declaration}=modules[${JSON.stringify(dependency)}];`;
 });
 source=source.replace(/\bexport\s+(async\s+function|function|class|const|let|var)\s+(\w+)/g,(_,type,name)=>{names.push(name);return `${type} ${name}`;});
 source=source.replace(/^export\s*\{([^}]+)\};?\s*$/gm,(_,list)=>{for(const entry of list.split(',')){const [local,alias]=entry.trim().split(/\s+as\s+/);names.push(alias?`${alias}:${local}`:local);}return '';});
 if(/^\s*(import|export)\s/m.test(source))throw Error('Unsupported module syntax in '+id);
 ordered.push(`modules[${JSON.stringify(id)}]=(()=>{\n${source}\nreturn {${names.join(',')}};\n})();`);
 return id;
}
compile(path.join(root,'src/street-game.js'));
const peerLibrary=fs.readFileSync(path.join(root,'src/vendor/peerjs.min.js'),'utf8');
const bundle='/* Generated by npm run build. Edit src/, not this file. PeerJS is MIT licensed; see src/vendor/peerjs.LICENSE. */\n'+peerLibrary+'\n(()=>{\n"use strict";\nconst modules=Object.create(null);\n'+ordered.join('\n')+'\n})();\n';
fs.writeFileSync(path.join(root,'public/game.bundle.js'),bundle);
let html=fs.readFileSync(path.join(root,'public/index.html'),'utf8');
html=html.replace(/<link rel="stylesheet" href="([^"]+)">/g,(_,file)=>'<style>'+fs.readFileSync(path.join(root,'public',file),'utf8').replace(/@import\s+url\([^)]*\)\s*;/g,'')+'</style>');
html=html.replace('<script src="game.bundle.js" defer></script>',()=>'<script>'+bundle.replace(/<\/script/gi,'<\\/script')+'</script>');
fs.writeFileSync(path.join(root,'index.html'),html);
console.log('Built standalone index.html and public/game.bundle.js ('+ordered.length+' modules).');
